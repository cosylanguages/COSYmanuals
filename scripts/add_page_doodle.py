"""Give English grammar topic pages a doodle that matches their vocabulary theme.

  * RULES maps a slug to a doodle name (first match wins, default "pencil").
  * The page gets data-doodle="<name>" on <main>; manual-look.css draws it in the page head as a CSS mask
    in the level accent colour (so it follows dark mode and prints in black).
  * `--css` rewrites the generated doodle block inside shared/styles/manual-look.css.
Doodle strokes are from COSYmagazine's doodle set (js/doodles.js); clock and house are new.
  python3 scripts/add_page_doodle.py [--check|--css] manuals/en/grammar
"""
