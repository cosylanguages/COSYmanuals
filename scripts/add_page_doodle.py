RULES = [  # (regex on slug, doodle): vocabulary theme in the examples
 (r"telling-time|^time|sequence|before-after|prepositions-time|tense|past|future|will|continuous|going-to|plans", "clock"),
 (r"frequency|present-simple|routine|simple-vs|habit", "sun"),
 (r"countable|much|many|some-vs|how-much|cost|id-like|quantif|all-both|too-vs|enough", "apple"),
 (r"place|there-is|there-was|there-are|prepositions", "house"),
 (r"like-love|possessive|have|family", "heart"),
 (r"comparative|superlative", "mountain"),
 (r"numbers|dates", "cake"),
 (r"around-world|travel", "ticket"),
 (r"question|word-order|imperative|pronoun|demonstr|be$|to-be|en-be|articles?$", "bubble"),
 (r"adjective|adverb|intensif|good-well|manner", "flower"),
 (r"plural|noun", "bookstack"),
 (r"work|collocation|play-do-go", "coffee"),
 (r"can|could|modal", "steps"),
 (r"if|conditional|alternatives", "ladder"),
 (r"confus|pattern|irregular|guide", "lightbulb"),
]

def doodle_for(slug):
    for rx, name in RULES:
        if re.search(rx, slug): return name
    return "pencil"

MAIN = re.compile(r'<main\b(?![^>]*\bdata-doodle=)', re.I)
START, END = "/* BEGIN doodles (generated by scripts/add_page_doodle.py --css) */", "/* END doodles */"

def css():
    out = [START,
      'main[data-doodle] .page-head::after { background:var(--ml-accent); opacity:.85; -webkit-mask:var(--ml-doodle, none) no-repeat center/contain; mask:var(--ml-doodle, none) no-repeat center/contain; }']
    out.append('@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) main[data-doodle] .page-head::after { background:var(--ml-accent); } }')
    out.append(':root[data-theme="dark"] main[data-doodle] .page-head::after { background:var(--ml-accent); }')
    for n, d in D.items():
        svg = ("<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 120 80' fill='none' stroke='black' stroke-width='2.6' "
               "stroke-linecap='round' stroke-linejoin='round'><path d='%s'/></svg>" % d)
        enc = svg.replace("<", "%3C").replace(">", "%3E").replace("#", "%23")
        out.append('main[data-doodle="%s"] { --ml-doodle:url("data:image/svg+xml,%s"); }' % (n, enc))
    out.append(END)
    return "\n".join(out)

def main():
    a = sys.argv[1:]
    if "--css" in a:
        p = pathlib.Path("shared/styles/manual-look.css"); s = p.read_text(encoding="utf8")
        if START in s: s = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: css(), s, flags=re.S)
        else:
            # replace the old inline pencil rule's background with the generated block, right after it
            s = s.replace("@media (max-width:520px) { .page-head { padding-right:0; }", css() + "\n@media (max-width:520px) { .page-head { padding-right:0; }", 1)
        p.write_text(s, encoding="utf8"); print("css block written"); return 0
    check = "--check" in a
    root = pathlib.Path([x for x in a if not x.startswith("--")][0]); n = 0
    for f in sorted(root.rglob("topics/*.html")):
        t = f.read_text(encoding="utf8")
        if 'class="page-head"' not in t: continue
        if not MAIN.search(t): continue
        n += 1
        if not check:
            f.write_text(MAIN.sub('<main data-doodle="%s"' % doodle_for(f.stem), t, count=1), encoding="utf8")
    print(("check: %d pages lacking data-doodle" if check else "added data-doodle to %d pages") % n)
    return 1 if check and n else 0

if __name__ == "__main__":
    sys.exit(main())
